// Package gendb is the lowest data-access layer. Controllers never touch it and
// never import database/sql directly; the *_db packages build SQL + args and
// call these helpers.
//
// Deviation from the HR service (documented on purpose): HR opens and closes a
// fresh *sql.DB on every call. This gateway is a long-running appliance on a
// Raspberry Pi with two always-on background workers (the pull collector and the
// forwarder) hitting the DB continuously, so it keeps ONE shared, pool-limited
// *sql.DB for the process lifetime. Pool limits are deliberately small to suit
// 4 GB of RAM.
package gendb

import (
	"context"
	"database/sql"
	"fmt"
	"sync"
	"time"

	milastructs "ismila/erp/zkbio/mila_structs"

	_ "github.com/go-sql-driver/mysql"
)

var (
	pool *sql.DB
	mu   sync.RWMutex
)

// Init opens the shared pool and verifies connectivity with a ping. Safe to call
// once at startup.
func Init(dsn string) error {
	db, err := sql.Open("mysql", dsn)
	if err != nil {
		return fmt.Errorf("gendb: open: %w", err)
	}
	// Conservative pool for a Pi: a handful of connections is plenty for the
	// management API + two workers, and keeps MariaDB's memory footprint down.
	db.SetMaxOpenConns(10)
	db.SetMaxIdleConns(5)
	db.SetConnMaxLifetime(30 * time.Minute)
	db.SetConnMaxIdleTime(5 * time.Minute)

	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	if err := db.PingContext(ctx); err != nil {
		return fmt.Errorf("gendb: ping: %w", err)
	}

	mu.Lock()
	pool = db
	mu.Unlock()
	return nil
}

// DB returns the shared pool. Panics if Init has not been called — a programming
// error, not a runtime condition.
func DB() *sql.DB {
	mu.RLock()
	defer mu.RUnlock()
	if pool == nil {
		panic("gendb: Init not called")
	}
	return pool
}

// Close closes the shared pool (called on graceful shutdown).
func Close() error {
	mu.Lock()
	defer mu.Unlock()
	if pool != nil {
		err := pool.Close()
		pool = nil
		return err
	}
	return nil
}

// SaveGeneral runs an INSERT (or any write) and returns rows affected. IDs are
// generated by MariaDB (DEFAULT UUID()), so LastInsertId is not used — re-select
// by a natural key when the new ID is needed.
func SaveGeneral(query string, args ...any) (int64, *milastructs.AnswerResponse) {
	ctx, cancel := context.WithTimeout(context.Background(), 15*time.Second)
	defer cancel()
	res, err := DB().ExecContext(ctx, query, args...)
	if err != nil {
		r := milastructs.Err("db write failed: " + err.Error())
		return 0, &r
	}
	n, _ := res.RowsAffected()
	ok := milastructs.Ok("ok", nil)
	return n, &ok
}

// UpdateGeneral runs an UPDATE/DELETE and returns rows affected.
func UpdateGeneral(query string, args ...any) (int64, *milastructs.AnswerResponse) {
	return SaveGeneral(query, args...)
}

// SelectGeneral runs a query and hands the rows to scan. scan must fully consume
// and close nothing (SelectGeneral closes the rows).
func SelectGeneral(scan func(*sql.Rows) error, query string, args ...any) *milastructs.AnswerResponse {
	ctx, cancel := context.WithTimeout(context.Background(), 20*time.Second)
	defer cancel()
	rows, err := DB().QueryContext(ctx, query, args...)
	if err != nil {
		r := milastructs.Err("db read failed: " + err.Error())
		return &r
	}
	defer rows.Close()
	if err := scan(rows); err != nil {
		r := milastructs.Err("db scan failed: " + err.Error())
		return &r
	}
	if err := rows.Err(); err != nil {
		r := milastructs.Err("db rows error: " + err.Error())
		return &r
	}
	ok := milastructs.Ok("ok", nil)
	return &ok
}

// SelectRow runs a single-row query for scanning into dest via row.Scan.
func SelectRow(query string, args ...any) *sql.Row {
	ctx := context.Background()
	return DB().QueryRowContext(ctx, query, args...)
}
